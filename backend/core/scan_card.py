    """Evidence-backed summary card of a Faraday scan/repair run."""
    findings_detected: int
    findings_resolved: int
    findings_remaining: int
    tests_verified: int
    execution_mode: str          # "Qualcomm Hexagon NPU (HTP v73)" or "CPU Fallback"
    passport_digest: str
    repo_revision: str
    timestamp: str

